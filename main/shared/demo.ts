export function demoReply(question: string, turn: number): string {
  if (/类似|练习/.test(question))
    return '试试这道题：3x + 2 = 11。\n你准备先对等式的两边做什么操作？先写出第一步就好。';
  if (/2x\s*=\s*6|两边.*减|减.*3/.test(question))
    return (
      '对，两边同时减去 3，得到 2x = 6。根据《一元一次方程 · 教学要点.txt》，接下来怎样让 x 的系数变成 1，同时保持两边相等？'
    );
  if (/2x|方程|答案|不会|开始/.test(question) || turn === 0)
    return (
      '我们先看这道题 2x + 3 = 9。\n根据《一元一次方程 · 教学要点.txt》，等式两边做相同的减法，等式仍然成立。\n想把左边的 +3 消去，两边应该同时减去什么？你可以先写出这一步。'
    );
  return (
    '暂时无法处理这个问题，请提供题目与解题步骤。'
  );
}
